"""
Unit and Integration Tests for Digital Notice Board System
"""

import unittest
import os
import json
from app import app
import database

class DigitalNoticeBoardTests(unittest.TestCase):

    def setUp(self):
        """Set up test environment and initialize test client."""
        app.config["TESTING"] = True
        app.config["WTF_CSRF_ENABLED"] = False
        self.client = app.test_client()
        # Initialize database and sample notices
        database.init_db()
        database.seed_sample_notices()

    def test_database_initialization_and_seeding(self):
        """Verify that sample notices and default admin are properly seeded."""
        notices = database.get_all_notices()
        self.assertGreaterEqual(len(notices), 5, "Database should contain at least 5 sample notices")
        
        # Verify default admin authentication
        admin = database.authenticate_admin("admin", "admin123")
        self.assertIsNotNone(admin, "Default admin authentication should succeed")
        self.assertEqual(admin["username"], "admin")

        # Verify invalid credentials fail
        invalid_admin = database.authenticate_admin("admin", "wrongpassword")
        self.assertIsNone(invalid_admin, "Invalid password authentication should return None")

    def test_public_homepage_and_filters(self):
        """Test public home page rendering, category filtering, and sorting."""
        response = self.client.get("/")
        self.assertEqual(response.status_code, 200)
        self.assertIn(b"Campus Digital Notice Board", response.data)
        self.assertIn(b"Examination", response.data)

        # Test category filter
        resp_exam = self.client.get("/?category=Examination")
        self.assertEqual(resp_exam.status_code, 200)
        self.assertIn(b"Examination", resp_exam.data)

        # Test search
        resp_search = self.client.get("/?q=Placement")
        self.assertEqual(resp_search.status_code, 200)
        self.assertIn(b"Placement", resp_search.data)

        # Test sorting
        resp_sort = self.client.get("/?sort=priority")
        self.assertEqual(resp_sort.status_code, 200)

    def test_single_notice_view_and_api(self):
        """Test single notice detail page and JSON API endpoint."""
        notices = database.get_all_notices()
        first_id = notices[0]["id"]

        # View full page
        resp_detail = self.client.get(f"/notice/{first_id}")
        self.assertEqual(resp_detail.status_code, 200)
        self.assertIn(b"OFFICIAL CAMPUS CIRCULAR", resp_detail.data)

        # JSON API
        resp_api = self.client.get(f"/api/notice/{first_id}")
        self.assertEqual(resp_api.status_code, 200)
        data = json.loads(resp_api.data.decode("utf-8"))
        self.assertTrue(data["success"])
        self.assertEqual(data["notice"]["id"], first_id)

    def test_admin_authentication_and_dashboard(self):
        """Test admin login flow, dashboard access, and route protection."""
        # Unauthenticated access to /admin should redirect to /login
        unauth_resp = self.client.get("/admin", follow_redirects=False)
        self.assertEqual(unauth_resp.status_code, 302)
        self.assertIn("/login", unauth_resp.headers["Location"])

        # Authenticate via POST /login
        login_resp = self.client.post("/login", data={
            "username": "admin",
            "password": "admin123"
        }, follow_redirects=True)
        self.assertEqual(login_resp.status_code, 200)
        self.assertIn(b"ADMINISTRATION CONSOLE", login_resp.data)

        # Post a new notice
        new_notice_resp = self.client.post("/admin/notice/new", data={
            "title": "Automated Unit Test Announcement Title",
            "category": "Academic",
            "priority": "Important",
            "posted_by": "Test Suite Runner",
            "expiry_date": "2026-12-31",
            "content": "This is a comprehensive test notice body generated by the unit testing framework.",
            "is_pinned": "1"
        }, follow_redirects=True)
        self.assertEqual(new_notice_resp.status_code, 200)
        self.assertIn(b"published successfully", new_notice_resp.data)

        # Verify notice was inserted
        searched = database.get_all_notices(search="Automated Unit Test")
        self.assertEqual(len(searched), 1)
        created_id = searched[0]["id"]

        # Toggle pin
        self.client.post(f"/admin/notice/toggle-pin/{created_id}", follow_redirects=True)
        updated = database.get_notice_by_id(created_id)
        self.assertEqual(updated["is_pinned"], 0)

        # Delete notice
        del_resp = self.client.post(f"/admin/notice/delete/{created_id}", follow_redirects=True)
        self.assertEqual(del_resp.status_code, 200)
        self.assertIsNone(database.get_notice_by_id(created_id))

        # Test Logout
        logout_resp = self.client.get("/logout", follow_redirects=True)
        self.assertEqual(logout_resp.status_code, 200)
        self.assertIn(b"You have been signed out successfully", logout_resp.data)

    def test_input_validation(self):
        """Test form validations for invalid or missing notice inputs."""
        # Log in first
        self.client.post("/login", data={"username": "admin", "password": "admin123"})

        # Try submitting an invalid short title
        resp = self.client.post("/admin/notice/new", data={
            "title": "Hi",  # Too short (< 5 chars)
            "category": "Academic",
            "priority": "Normal",
            "posted_by": "Dean",
            "content": "Valid length content here..."
        }, follow_redirects=True)
        self.assertIn(b"Notice title must be at least 5 characters long", resp.data)

        # Try submitting short content
        resp2 = self.client.post("/admin/notice/new", data={
            "title": "Valid Notice Title",
            "category": "Academic",
            "priority": "Normal",
            "posted_by": "Dean",
            "content": "Short"  # Too short (< 10 chars)
        }, follow_redirects=True)
        self.assertIn(b"Notice content must be at least 10 characters long", resp2.data)


if __name__ == "__main__":
    unittest.main()

